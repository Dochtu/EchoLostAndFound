using System;
using EchoLostAndFound.M2;

namespace EchoStation
{
    /// <summary>
    /// Chapter-01 scene targets that the investigation slice exposes to the player.
    /// Values are append-only: the greybox scene stores labels, not enum values, so
    /// adding a target never rewrites an existing scene.
    /// </summary>
    public enum StationTarget
    {
        Unknown = 0,
        Watch = 1,
        Cabinet = 2,
        LostPackage = 3,
        Binder = 4,
        Laozhou = 5,
        Linyao = 6
    }

    /// <summary>
    /// Maps an interactable's approved scene label to a chapter-01 investigation target.
    /// Labels are the player-facing Chinese names generated by the greybox scene; the
    /// interaction kind must also match, so a mis-labelled prop stays inert instead of
    /// silently opening the wrong panel.
    /// </summary>
    public static class StationTargets
    {
        public const string WatchLabel = "怀表";
        public const string CabinetLabel = "维修柜";
        public const string LostPackageLabel = "失物包";
        public const string BinderLabel = "副联册";
        public const string LaozhouLabel = "老周";
        public const string LinyaoLabel = "林遥";

        public const string NpcLaozhou = "npc_laozhou";
        public const string NpcLinyao = "npc_linyao";

        /// <summary>Evidence cards reachable from a target; null when the target grants none.</summary>
        public static string EvidenceId(StationTarget target)
        {
            switch (target)
            {
                case StationTarget.Watch: return "E01";
                case StationTarget.Cabinet: return "E02";
                case StationTarget.LostPackage: return "E03";
                case StationTarget.Binder: return "E04";
                default: return null;
            }
        }

        /// <summary>The NPC conversation a target starts; null for non-NPC targets.</summary>
        public static string NpcId(StationTarget target)
        {
            switch (target)
            {
                case StationTarget.Laozhou: return NpcLaozhou;
                case StationTarget.Linyao: return NpcLinyao;
                default: return null;
            }
        }

        public static StationTarget Resolve(string displayName, InteractionKind kind)
        {
            var label = displayName == null ? string.Empty : displayName.Trim();
            if (label.Length == 0) return StationTarget.Unknown;
            if (Is(label, WatchLabel) && kind == InteractionKind.Item) return StationTarget.Watch;
            if (Is(label, CabinetLabel) && kind == InteractionKind.Document) return StationTarget.Cabinet;
            if (Is(label, LostPackageLabel) && kind == InteractionKind.Document) return StationTarget.LostPackage;
            if (Is(label, BinderLabel) && kind == InteractionKind.Document) return StationTarget.Binder;
            if (Is(label, LaozhouLabel) && kind == InteractionKind.Npc) return StationTarget.Laozhou;
            if (Is(label, LinyaoLabel) && kind == InteractionKind.Npc) return StationTarget.Linyao;
            return StationTarget.Unknown;
        }

        static bool Is(string label, string approved) => string.Equals(label, approved, StringComparison.Ordinal);
    }
}
